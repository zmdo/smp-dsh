import { mkdirSync, writeFileSync } from 'node:fs'

const required = ['DATABASE_URL', 'ENCRYPTION_KEY', 'SESSION_SECRET']
for (const key of required) {
  if (!process.env[key]) throw new Error(`${key} is required`)
}

const quote = (value) => JSON.stringify(String(value))
const profile = '/dsh-home/profiles/web'
mkdirSync(`${profile}`, { recursive: true })
mkdirSync('/srv/workspaces', { recursive: true })
mkdirSync('/srv/components', { recursive: true })

const patch = `# Generated by /app/docker/render-profile.mjs
- id: smp-database
  config:
    databaseUrl: ${quote(process.env.DATABASE_URL)}
    encryptionKey: ${quote(process.env.ENCRYPTION_KEY)}
- id: smp-frame
  config:
    sessionSecret: ${quote(process.env.SESSION_SECRET)}
    initialUsername: ${quote(process.env.INITIAL_USERNAME ?? 'admin')}
    initialPassword: ${quote(process.env.INITIAL_PASSWORD ?? 'changeme')}
- id: smp-workspace-storage
  config:
    importRoot: /srv/workspaces
- id: smp-server-management
  config:
    inspectIntervalSeconds: 30
    metricsIntervalSeconds: 1
- id: smp-install
  disabled: true
- id: locale
  name: "@deepseek-ai/dsh-client-locale"
  config:
    preference: zh
`
writeFileSync(`${profile}/cordis.patch.yml`, patch, { mode: 0o600 })
writeFileSync(`${profile}/install-complete`, '')
