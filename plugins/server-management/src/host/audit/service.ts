import type { Db } from '../database/connection.ts'
import { readTransaction } from '../database/transaction.ts'
import { auditCount, auditRecords, type AuditListQuery } from './persistence/repository.ts'

export async function listAuditRecords(db: Db, query: AuditListQuery) {
  const [rows, count] = await readTransaction(db, (client) =>
    Promise.all([auditRecords(client, query), auditCount(client, query)]),
  )
  return {
    items: rows.rows.map((row) => ({
      id: row.id,
      server_id: row.server_id,
      server_name: row.server_name,
      host: row.host,
      actor_id: row.actor_id,
      actor_kind: row.actor_kind,
      harness_session_id: row.harness_session_id,
      agent_id: row.agent_id,
      harness_turn: row.harness_turn,
      harness_step: row.harness_step,
      harness_event_seq: row.harness_event_seq === null ? null : Number(row.harness_event_seq),
      tool_call_id: row.tool_call_id,
      root_tool_call_id: row.root_tool_call_id,
      parent_tool_call_id: row.parent_tool_call_id,
      tool_name: row.tool_name,
      permission_mode: row.permission_mode,
      approval_status: row.approval_status,
      approval_id: row.approval_id,
      approved_by: row.approved_by,
      approved_at: row.approved_at?.toISOString() ?? null,
      approval_reason: row.approval_reason,
      command: row.command,
      command_digest: row.command_digest,
      command_length: row.command_length,
      command_truncated: row.command_truncated,
      redaction_applied: row.redaction_applied,
      cwd: row.cwd,
      status: row.status,
      started_at: row.started_at.toISOString(),
      finished_at: row.finished_at?.toISOString() ?? null,
      duration_ms: row.duration_ms,
      exit_code: row.exit_code,
      signal: row.signal,
      timed_out: row.timed_out,
      cancelled: row.cancelled,
      error_code: row.error_code,
      error_message: row.error_message,
      stdout_excerpt: row.stdout_excerpt,
      stderr_excerpt: row.stderr_excerpt,
      stdout_bytes: row.stdout_bytes === null ? null : Number(row.stdout_bytes),
      stderr_bytes: row.stderr_bytes === null ? null : Number(row.stderr_bytes),
      stdout_truncated: row.stdout_truncated,
      stderr_truncated: row.stderr_truncated,
      stdout_digest: row.stdout_digest,
      stderr_digest: row.stderr_digest,
      created_at: row.created_at.toISOString(),
    })),
    total: count.rows[0]?.count ?? 0,
    page: query.page,
    page_size: query.pageSize,
  }
}
